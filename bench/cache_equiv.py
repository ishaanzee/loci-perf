def post(base, path, body, timeout=900):
    req = urllib.request.Request(base + path, data=json.dumps(body).encode(),
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read())


def render(base, messages, template_kwargs):
    body = {"messages": messages}
    if template_kwargs:
        body["chat_template_kwargs"] = template_kwargs
    return post(base, "/apply-template", body)["prompt"]


def complete(base, prompt, n_predict, k, cache):
    t0 = time.perf_counter()
    r = post(base, "/completion", {
        "prompt": prompt, "n_predict": n_predict, "temperature": 0.0, "seed": 0,
        "n_probs": k, "cache_prompt": cache, "stream": False,
    })
    r["_wall_s"] = time.perf_counter() - t0
    return r


def probs(r):
    """Per generated token: (chosen id, chosen logprob, {id: logprob} for the top-k)."""
    out = []
    for p in r.get("completion_probabilities", []):
        top = {t["id"]: t["logprob"] for t in p.get("top_logprobs", [])}
        out.append((p["id"], p["logprob"], top))
    return out


def kl_topk(ref_top, test_top):
    """KL(ref || test) restricted to ref's top-k tokens, both renormalised over that set (so it is
    >= 0). Tokens missing from test's top-k get test's lowest top-k logprob, an upper bound on
    their true value. An approximation of the full-vocabulary KL, good for comparing runs."""
    if not ref_top or not test_top:
        return float("nan")
    floor = min(test_top.values())
    ids = list(ref_top)
    p = [math.exp(ref_top[i]) for i in ids]
    q = [math.exp(test_top.get(i, floor)) for i in ids]
    sp, sq = sum(p), sum(q)
    return max(0.0, sum(pi / sp * math.log((pi / sp) / (qi / sq)) for pi, qi in zip(p, q)))


def compare(a, b):
    ta, tb = [x[0] for x in a], [x[0] for x in b]
    n = min(len(ta), len(tb))
    div = next((i for i in range(n) if ta[i] != tb[i]), None)
    if div is None and len(ta) != len(tb):
        div = n
    upto = n if div is None else div
    kls = [kl_topk(a[i][2], b[i][2]) for i in range(upto)]
    kls = [x for x in kls if not math.isnan(x)]
    dlp = [abs(a[i][1] - b[i][1]) for i in range(upto)]
    margin = None
    if div is not None and div < len(a):
        top = sorted(a[div][2].values(), reverse=True)
        if len(top) >= 2:
            margin = top[0] - top[1]
    return {
        "identical": div is None, "first_div": div, "n_ref": len(ta), "n_test": len(tb),
        "margin_at_div": margin,
        "kl_mean": sum(kls) / len(kls) if kls else None, "kl_max": max(kls) if kls else None,
        "dlogp_max": max(dlp) if dlp else None,
    }


def verdict(c, near_tie):
    if c["identical"]:
        return "identical"
    if c["margin_at_div"] is not None and c["margin_at_div"] < near_tie:
        return "near-tie flip"
    return "INVESTIGATE"


def timing(r):
    t = r.get("timings", {})
    return {"cache_n": t.get("cache_n", r.get("tokens_cached")), "prompt_n": t.get("prompt_n"),
            "prompt_ms": t.get("prompt_ms"), "predicted_per_second": t.get("predicted_per_second")}


def start_server(args, log_path):
    cmd = [args.llama_server, "-m", str(args.model), "-c", str(args.ctx), "-np", "1", "-fa", "on",
           "-cram", "0", "--host", "127.0.0.1", "--port", str(args.port)]
    if args.swa_full:
        cmd.append("--swa-full")
    cmd += args.server_arg
    print("starting:", " ".join(cmd))
    log = open(log_path, "w")
    proc = subprocess.Popen(cmd, stdout=log, stderr=subprocess.STDOUT)
    base = f"http://127.0.0.1:{args.port}"
    deadline = time.time() + 300
    while time.time() < deadline:
        if proc.poll() is not None:
            sys.exit(f"llama-server exited early; see {log_path}")
        try:
            with urllib.request.urlopen(base + "/health", timeout=2) as r:
                if r.status == 200:
                    return proc, base
        except (urllib.error.URLError, ConnectionError, OSError):
            pass
        time.sleep(1)
    proc.terminate()
    sys.exit(f"llama-server not ready after 300 s; see {log_path}")


def run_case(base, case, args, tk):
    # 1. Build the history: the model answers each earlier turn (greedy, cache on - only the
    #    final question is under test).
    msgs = []
    for q in case["turns"]:
        msgs.append({"role": "user", "content": q})
        r = complete(base, render(base, msgs, tk), args.history_tokens, 0, True)
        msgs.append({"role": "assistant", "content": r["content"].strip()})
    msgs.append({"role": "user", "content": case["final"]})
    full = render(base, msgs, tk)

    # The warm prompt must be an exact text prefix of the full one: cut just before the last
    # user message. The server reuses the longest common token prefix.
    cut = full.rfind(case["final"])
    warm = full[:cut]

    ref1 = complete(base, full, args.gen, args.k, False)
    ref2 = complete(base, full, args.gen, args.k, False)
    complete(base, warm, 1, 0, True)
    cached = complete(base, full, args.gen, args.k, True)

    p1, p2, pc = probs(ref1), probs(ref2), probs(cached)
    noise = compare(p1, p2)
    reuse = compare(p1, pc)
    return {
        "case": case["name"], "prompt_tokens": ref1.get("tokens_evaluated"),
        "ref": timing(ref1), "cached": timing(cached),
        "noise_floor": noise, "reuse": reuse, "verdict": verdict(reuse, args.near_tie),
        "ref_text": ref1.get("content", "")[:400], "cached_text": cached.get("content", "")[:400],
    }


def fmt(x, nd=4):
    return "-" if x is None else (f"{x:.{nd}g}" if isinstance(x, float) else str(x))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model", type=Path, default=LOCI_MODEL)
    ap.add_argument("--server", help="use a running llama-server (start it with -np 1) instead")
    ap.add_argument("--llama-server", default="llama-server")
    ap.add_argument("--port", type=int, default=8091)
    ap.add_argument("--ctx", type=int, default=8192)
    ap.add_argument("--swa-full", action="store_true", help="full-size sliding-window KV cache")
    ap.add_argument("--server-arg", action="append", default=[], help="extra llama-server arg (repeatable)")
    ap.add_argument("--cases", type=int, default=len(CASES))
    ap.add_argument("--gen", type=int, default=128, help="tokens generated per compared request")
    ap.add_argument("--history-tokens", type=int, default=200, help="tokens per earlier answer")
    ap.add_argument("--k", type=int, default=20, help="top-k logprobs per token")
    ap.add_argument("--near-tie", type=float, default=0.05, help="margin (nats) counted as a near-tie")
    ap.add_argument("--template-kwargs", default='{"enable_thinking": false}',
                    help="JSON passed to the chat template ('' for none)")
    args = ap.parse_args()

    RESULTS.mkdir(parents=True, exist_ok=True)
    stamp = dt.datetime.now().strftime("%Y%m%d-%H%M%S")
    out_path = RESULTS / f"cache_equiv-{stamp}.jsonl"
    tk = json.loads(args.template_kwargs) if args.template_kwargs else None

    proc = None
    if args.server:
        base = args.server.rstrip("/")
    else:
        if not args.model.exists():
            sys.exit(f"model not found: {args.model}")
        proc, base = start_server(args, RESULTS / f"llama-server-{stamp}.log")

    rows = []
    try:
        with open(out_path, "w") as f:
            for case in CASES[:args.cases]:
                print(f"case {case['name']} ...", flush=True)
                row = run_case(base, case, args, tk)
                rows.append(row)
                f.write(json.dumps(row) + "\n")
                f.flush()
            summary = {
                "summary": True, "model": args.server or str(args.model), "swa_full": args.swa_full,
                "gen": args.gen, "k": args.k,
                "identical": sum(r["verdict"] == "identical" for r in rows),
                "near_tie": sum(r["verdict"] == "near-tie flip" for r in rows),
                "investigate": sum(r["verdict"] == "INVESTIGATE" for r in rows),
                "noise_floor_identical": all(r["noise_floor"]["identical"] for r in rows),
            }
            f.write(json.dumps(summary) + "\n")
    finally:
        if proc:
            proc.terminate()
            proc.wait(timeout=30)

    hdr = ["case", "prompt", "cache_n", "prefilled", "ref ms", "cached ms", "noise", "verdict",
           "first_div", "margin", "kl_mean", "kl_max", "dlogp_max"]
    print("\n" + " | ".join(hdr))
    for r in rows:
        u = r["reuse"]
        print(" | ".join(fmt(x) for x in [
            r["case"], r["prompt_tokens"], r["cached"]["cache_n"], r["cached"]["prompt_n"],
            r["ref"]["prompt_ms"], r["cached"]["prompt_ms"],
            "ok" if r["noise_floor"]["identical"] else "NOT DETERMINISTIC", r["verdict"],
            u["first_div"], u["margin_at_div"], u["kl_mean"], u["kl_max"], u["dlogp_max"]]))
    if any((r["cached"]["cache_n"] or 0) < 0.5 * (r["prompt_tokens"] or 1) for r in rows):
        print("\nWARNING: some cases reused under half the prompt. The sliding-window cache may be "
              "blocking reuse; rerun with --swa-full.")
    print(f"\nwrote {out_path}")


if __name__ == "__main__":
    main()
