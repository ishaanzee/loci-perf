#!/usr/bin/env python3
"""Does reusing the prompt cache change the model's answers? (report §6)

Loci re-reads its whole ~4.2k-token prompt on every request (0% from the prefix cache). The fix
is to reuse the cached KV for the part of the prompt that hasn't changed. That changes no model
weights, but it does change the *shapes* the GPU sees: the full path prefills ~4k tokens in big
batches (ggml-metal's matrix-matrix kernels), while the cached path prefills only the new ~30
tokens (small batch, often the matrix-vector kernels). Different kernels sum in a different order,
so the logits can move a little. That is the same class of bug as the Winograd conv2d issue: a
shape-dependent kernel path that silently changes numerics.

This script measures it on Loci's own GGUF with stock llama-server, for each test conversation:

  ref1, ref2   full prompt, cache off (cache_prompt=false) -> the reference, run twice so we know
               the noise floor (should be bit-identical)
  warm         everything except the last user message, cache on -> fills the KV cache
  cached       full prompt, cache on -> only the new tokens are prefilled

and compares cached vs ref1 token by token (greedy, temperature 0):

  identical        same output tokens, start to end
  first_div        index of the first different token (None if identical)
  margin_at_div    ref's top-1 minus top-2 logprob at that point. A flip on a near-tie (tiny
                   margin) is expected float reordering; a flip with a wide margin is a bug.
  kl_mean/kl_max   approximate KL(ref || cached) per position, over ref's top-k tokens, on the
                   positions before the first divergence (where both runs saw the same context)
  dlogp_max        largest |change| in the logprob of the chosen token over those positions
  cache_n/prompt_n tokens taken from the cache vs actually prefilled, so you can see that reuse
                   really happened. If cache_n is ~0, the sliding-window cache blocked reuse:
                   rerun with --swa-full.

It also reports prefill time (prompt_ms) for ref vs cached, which is the speedup itself.

Run with Loci quit and the Mac quiet. Stdlib only. Examples:
  python3 cache_equiv.py                       # starts llama-server on Loci's GGUF, 5 cases
  python3 cache_equiv.py --swa-full            # full-size sliding-window cache
  python3 cache_equiv.py --server http://127.0.0.1:8090   # use a server you started (-np 1)
  python3 cache_equiv.py --cases 2 --gen 64    # quick run
Results: ../results/cache_equiv-<time>.jsonl (one line per case plus a summary line).
"""

